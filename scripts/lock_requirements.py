"""Write requirements.lock: exact versions of everything requirements.txt pulls in.

The lock is taken from the *installed* environment, not resolved fresh, so it
records a set that is known to work (run ``python scripts/check_gpu.py`` and
the app first). Reinstall it exactly with::

    pip install -r requirements.lock

(paddlepaddle-gpu still comes from the Paddle index; see README.)

Run with the interpreter the app uses: ``py -3.12 scripts/lock_requirements.py``.
"""

import importlib.metadata as md
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS = ROOT / "requirements.txt"
CONSTRAINTS = ROOT / "constraints-gpu.txt"
LOCK = ROOT / "requirements.lock"

_NAME = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)")


def _canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _top_level(path: Path) -> list[str]:
    names = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        match = _NAME.match(line)
        if match:
            names.append(match.group(1))
    return names


def _requires(dist: md.Distribution) -> list[str]:
    """Runtime requirements that apply here (extras and other platforms skipped)."""
    from packaging.requirements import Requirement

    names = []
    for spec in dist.requires or []:
        req = Requirement(spec)
        if req.marker and not req.marker.evaluate({"extra": ""}):
            continue
        names.append(req.name)
    return names


def main() -> int:
    installed = {_canonical(d.metadata["Name"]): d for d in md.distributions()}
    pending = _top_level(REQUIREMENTS) + _top_level(CONSTRAINTS)
    missing, locked = [], {}
    while pending:
        name = _canonical(pending.pop())
        if name in locked:
            continue
        dist = installed.get(name)
        if dist is None:
            missing.append(name)
            continue
        locked[name] = dist
        pending.extend(_requires(dist))

    if missing:
        print(
            "Not installed (install requirements.txt first):",
            ", ".join(sorted(set(missing))),
        )
        return 1

    lines = [
        "# Generated by scripts/lock_requirements.py from a verified environment.",
        f"# Python {sys.version.split()[0]}; regenerate after changing requirements.txt",
        "# or constraints-gpu.txt (and after scripts/check_gpu.py passes).",
        "#   pip install -r requirements.lock",
        "",
    ]
    lines += [f"{d.metadata['Name']}=={d.version}" for _, d in sorted(locked.items())]
    LOCK.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {LOCK.name}: {len(locked)} packages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
